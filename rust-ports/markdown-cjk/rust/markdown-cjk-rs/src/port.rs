//! The Rust port of `src/qwenpaw/utils/markdown_cjk.py`.
//!
//! Behavioural port of `normalize_cjk_emphasis` and its helpers. The source
//! works on Python code points (``len(text)``) and per-code-point byte masks,
//! so this port works on ``Vec<char>`` and parallel ``Vec<bool>`` masks; the
//! observable result (the returned string) is what `rust-anything diff`
//! compares, and it is identical.
//!
//! Two tables are generated from Python's own ``unicodedata`` so the
//! classification matches the original exactly rather than approximating it:
//! the category-P/S set used for CommonMark flanking, and ``str.isspace``.
//! They live in `unitables.rs` and are regenerated by
//! `features/rust-port/gen_unitables.py`.

#![forbid(unsafe_code)]

use crate::unitables::{is_py_punctuation_or_symbol, is_py_space};

pub const CORE_PUNCTUATION: [char; 8] = [
    '\u{3002}', '\u{FF01}', '\u{FF1F}', '\u{FF1B}', '\u{FF1A}', '\u{FF0C}', '\u{3001}', '\u{2026}',
];
pub const TRAILING_CLOSERS: [char; 10] = [
    '\u{201D}', '\u{2019}', '\u{300D}', '\u{300F}', '\u{3011}', '\u{300B}', '\u{3009}', '\u{FF09}',
    '\u{3015}', '\u{FF3D}',
];

const CJK_RANGES: &[(u32, u32)] = &[
    (0x2E80, 0x2EFF),
    (0x3005, 0x3005),
    (0x3007, 0x3007),
    (0x3021, 0x3029),
    (0x3038, 0x303B),
    (0x3041, 0x3096),
    (0x309D, 0x309F),
    (0x30A1, 0x30FA),
    (0x30FD, 0x30FF),
    (0x31F0, 0x31FF),
    (0xFF66, 0xFF9D),
    (0x3400, 0x4DBF),
    (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF),
    (0x1100, 0x11FF),
    (0x3130, 0x318F),
    (0xA960, 0xA97F),
    (0xAC00, 0xD7A3),
    (0xD7B0, 0xD7FF),
    (0x20000, 0x2A6DF),
    (0x2A700, 0x2EBEF),
    (0x2F800, 0x2FA1F),
];

fn is_cjk(c: char) -> bool {
    let p = c as u32;
    CJK_RANGES.iter().any(|&(a, b)| a <= p && p <= b)
}

fn in_core_punctuation(c: char) -> bool {
    CORE_PUNCTUATION.contains(&c)
}

fn in_trailing_closers(c: char) -> bool {
    TRAILING_CLOSERS.contains(&c)
}

/// (punctuation_start, delimiter_start, delimiter_end)
type Replacement = (usize, usize, usize);

/// Port of `normalize_cjk_emphasis` (`src/qwenpaw/utils/markdown_cjk.py:98`).
pub fn normalize_cjk_emphasis(text: String) -> Result<String, String> {
    if text.is_empty() {
        return Ok(text);
    }
    let chars: Vec<char> = text.chars().collect();
    let (block, protected, paragraph_reset) = build_protection_masks(&chars);
    let mut replacements: Vec<Replacement> = Vec::new();
    let mut delimiters: Vec<(char, usize)> = Vec::new();
    let mut was_block = false;

    let length = chars.len();
    let mut index = 0usize;
    while index < length {
        if paragraph_reset[index] {
            delimiters.clear();
        }

        if block[index] {
            if !was_block {
                delimiters.clear();
            }
            was_block = true;
            index += 1;
            continue;
        }
        if was_block {
            delimiters.clear();
            was_block = false;
        }
        if protected[index] {
            index += 1;
            continue;
        }

        let character = chars[index];
        if character != '*' && character != '_' {
            index += 1;
            continue;
        }

        let run_length = count_run(&chars, &protected, index, character);
        if !(run_length == 1 || run_length == 2 || run_length == 3) {
            index += run_length;
            continue;
        }
        if is_escaped(&chars, index) {
            index += run_length;
            continue;
        }

        let punctuation_start = find_trailing_punctuation_start(&chars, index);
        let mut matching_top = false;
        if let Some(&(top_character, top_length)) = delimiters.last() {
            matching_top = top_character == character && top_length == run_length;
        }
        let is_repair_candidate = punctuation_start >= 0
            && is_cjk_at(&chars, index + run_length)
            && range_unprotected(&protected, punctuation_start as usize, index + run_length);

        if is_repair_candidate && matching_top {
            delimiters.pop();
            replacements.push((punctuation_start as usize, index, index + run_length));
            index += run_length;
            continue;
        }

        let (can_open, can_close) = delimiter_flanking(&chars, index, run_length);
        if can_close && matching_top {
            delimiters.pop();
        } else if can_open {
            delimiters.push((character, run_length));
        }
        index += run_length;
    }

    if replacements.is_empty() {
        return Ok(text);
    }

    let mut output = String::new();
    let mut copied_through = 0usize;
    for (punct_start, delim_start, delim_end) in replacements {
        output.extend(chars[copied_through..punct_start].iter());
        output.extend(chars[delim_start..delim_end].iter());
        output.extend(chars[punct_start..delim_start].iter());
        copied_through = delim_end;
    }
    output.extend(chars[copied_through..].iter());
    Ok(output)
}

/// Port of `_build_protection_masks`.
fn build_protection_masks(chars: &[char]) -> (Vec<bool>, Vec<bool>, Vec<bool>) {
    let length = chars.len();
    let mut block = vec![false; length];
    let mut paragraph_reset = vec![false; length + 1];
    let mut fence: Option<(char, usize)> = None;

    let mut line_start = 0usize;
    while line_start < length {
        let newline = find_char_from(chars, '\n', line_start);
        let line_end_with_newline = match newline {
            None => length,
            Some(n) => n + 1,
        };
        let mut content_end = match newline {
            None => length,
            Some(n) => n,
        };
        if content_end > line_start && chars[content_end - 1] == '\r' {
            content_end -= 1;
        }
        let line: Vec<char> = chars[line_start..content_end].to_vec();

        match fence {
            Some(f) => {
                for slot in block
                    .iter_mut()
                    .take(line_end_with_newline)
                    .skip(line_start)
                {
                    *slot = true;
                }
                if is_closing_fence(&line, f) {
                    fence = None;
                }
            }
            None => {
                if let Some(opening) = get_opening_fence(&line) {
                    fence = Some(opening);
                    for slot in block
                        .iter_mut()
                        .take(line_end_with_newline)
                        .skip(line_start)
                    {
                        *slot = true;
                    }
                } else if is_indented(&line) {
                    for slot in block
                        .iter_mut()
                        .take(line_end_with_newline)
                        .skip(line_start)
                    {
                        *slot = true;
                    }
                } else if is_blank(&line) {
                    paragraph_reset[line_start] = true;
                    paragraph_reset[line_end_with_newline] = true;
                }
            }
        }
        line_start = line_end_with_newline;
    }

    let mut protected = block.clone();
    mark_inline_code(chars, &block, &mut protected);
    (block, protected, paragraph_reset)
}

fn find_char_from(chars: &[char], needle: char, from: usize) -> Option<usize> {
    (from..chars.len()).find(|&i| chars[i] == needle)
}

/// Port of `_get_opening_fence`: `^( {0,3})(`{3,}|~{3,})(.*)$`.
fn get_opening_fence(line: &[char]) -> Option<(char, usize)> {
    let mut i = 0usize;
    let mut spaces = 0usize;
    while i < line.len() && line[i] == ' ' && spaces < 3 {
        i += 1;
        spaces += 1;
    }
    if line.len() < i + 3 {
        return None;
    }
    let marker = line[i];
    if marker != '`' && marker != '~' {
        return None;
    }
    let mut run = 0usize;
    while i + run < line.len() && line[i + run] == marker {
        run += 1;
    }
    if run < 3 {
        return None;
    }
    let rest = &line[i + run..];
    if marker == '`' && rest.contains(&'`') {
        return None;
    }
    Some((marker, run))
}

/// Port of `_is_closing_fence`.
fn is_closing_fence(line: &[char], fence: (char, usize)) -> bool {
    let offset = line.iter().take_while(|&&c| c == ' ').count().min(3);
    let mut end = offset;
    while end < line.len() && line[end] == fence.0 {
        end += 1;
    }
    end - offset >= fence.1 && is_blank(&line[end..])
}

/// Port of `_INDENT_RE` = `^(?: {4}|\t)`.
fn is_indented(line: &[char]) -> bool {
    if line.len() >= 4 && line[0] == ' ' && line[1] == ' ' && line[2] == ' ' && line[3] == ' ' {
        return true;
    }
    !line.is_empty() && line[0] == '\t'
}

/// Port of `_BLANK_RE` = `^[ \t]*$`.
fn is_blank(line: &[char]) -> bool {
    line.iter().all(|&c| c == ' ' || c == '\t')
}

/// Port of `_mark_inline_code`.
fn mark_inline_code(chars: &[char], block: &[bool], protected: &mut [bool]) {
    let length = chars.len();
    let mut index = 0usize;
    while index < length {
        if block[index] || chars[index] != '`' || is_escaped(chars, index) {
            index += 1;
            continue;
        }

        let opening_length = count_character_run(chars, index, '`');
        let mut closing_start: Option<usize> = None;
        let mut cursor = index + opening_length;
        while cursor < length {
            if block[cursor] {
                break;
            }
            if chars[cursor] != '`' || is_escaped(chars, cursor) {
                cursor += 1;
                continue;
            }
            let closing_length = count_character_run(chars, cursor, '`');
            if closing_length == opening_length {
                closing_start = Some(cursor);
                break;
            }
            cursor += closing_length;
        }

        match closing_start {
            None => {
                for slot in protected.iter_mut().skip(index) {
                    *slot = true;
                }
                return;
            }
            Some(start) => {
                let end = start + opening_length;
                for slot in protected.iter_mut().take(end).skip(index) {
                    *slot = true;
                }
                index = end;
            }
        }
    }
}

/// Port of `_count_run`.
fn count_run(chars: &[char], protected: &[bool], start: usize, character: char) -> usize {
    let mut end = start;
    let length = chars.len();
    while end < length && !protected[end] && chars[end] == character {
        end += 1;
    }
    end - start
}

/// Port of `_count_character_run`.
fn count_character_run(chars: &[char], start: usize, character: char) -> usize {
    let mut end = start;
    let length = chars.len();
    while end < length && chars[end] == character {
        end += 1;
    }
    end - start
}

/// Port of `_is_escaped`.
fn is_escaped(chars: &[char], index: usize) -> bool {
    let mut backslashes = 0usize;
    let mut cursor = index as isize - 1;
    while cursor >= 0 && chars[cursor as usize] == '\\' {
        backslashes += 1;
        cursor -= 1;
    }
    backslashes % 2 == 1
}

/// Port of `_find_trailing_punctuation_start`.
fn find_trailing_punctuation_start(chars: &[char], end: usize) -> isize {
    let mut cursor = end;
    while cursor > 0 && in_trailing_closers(chars[cursor - 1]) {
        cursor -= 1;
    }
    let before_core = cursor;
    while cursor > 0 && in_core_punctuation(chars[cursor - 1]) {
        cursor -= 1;
    }
    if cursor < before_core {
        cursor as isize
    } else {
        -1
    }
}

/// Port of `_is_cjk_at`.
fn is_cjk_at(chars: &[char], index: usize) -> bool {
    if index >= chars.len() {
        return false;
    }
    is_cjk(chars[index])
}

/// Port of `_range_unprotected`.
fn range_unprotected(protected: &[bool], start: usize, end: usize) -> bool {
    !protected[start..end].iter().any(|&p| p)
}

/// Port of `_delimiter_flanking`.
fn delimiter_flanking(chars: &[char], start: usize, length: usize) -> (bool, bool) {
    let previous = if start > 0 {
        Some(chars[start - 1])
    } else {
        None
    };
    let following = if start + length < chars.len() {
        Some(chars[start + length])
    } else {
        None
    };

    let previous_whitespace = match previous {
        None => true,
        Some(c) => is_py_space(c),
    };
    let next_whitespace = match following {
        None => true,
        Some(c) => is_py_space(c),
    };
    let previous_punctuation = match previous {
        None => false,
        Some(c) => is_py_punctuation_or_symbol(c),
    };
    let next_punctuation = match following {
        None => false,
        Some(c) => is_py_punctuation_or_symbol(c),
    };

    let left_flanking =
        (!next_whitespace) && ((!next_punctuation) || previous_whitespace || previous_punctuation);
    let right_flanking =
        (!previous_whitespace) && ((!previous_punctuation) || next_whitespace || next_punctuation);

    if chars[start] == '*' {
        return (left_flanking, right_flanking);
    }
    (
        left_flanking && ((!right_flanking) || previous_punctuation),
        right_flanking && ((!left_flanking) || next_punctuation),
    )
}
